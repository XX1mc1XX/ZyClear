#ifndef EXTENSIONHOST_H
#define EXTENSIONHOST_H

class QMainWindow;
class PanelRegistry;

// =============================================================================
// 扩展宿主：把登记在册的面板挂到主窗口上
//
// 【为什么单独一层】主窗口不该知道「有哪些面板」。
//   它只调一次 Attach，剩下的事（造面板、包成停靠窗、加进视图菜单）都在这里。
//   新增面板时主窗口一行都不用改 —— 这正是契约层要的效果。
//
// 【为什么用 QDockWidget 而不是把面板塞进 splitter】
//   splitter 是个等分容器：每一栏都要一直占着宽度，关不掉也挪不走。
//   而「AI 助手」和「日志」属于用时才打开的东西，不该长期挤占图像区的宽度。
//   QDockWidget 天然支持停靠到任意边、浮动成独立窗口、右上角关掉、从菜单再打开，
//   正是 VS Code 那套侧边栏与底部面板的行为。
// =============================================================================

class ExtensionHost {
public:
    // 把注册处里的面板全部挂到主窗口。
    // 会顺带在菜单栏建一个「视图」菜单，用于重新打开被关掉的面板。
    // 返回实际挂上去的面板数量。
    static int Attach(QMainWindow* window, PanelRegistry* registry);
};

#endif
